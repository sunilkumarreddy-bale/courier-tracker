CREATE TABLE IF NOT EXISTS users (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(300) NOT NULL,
 role ENUM('ADMIN','AGENT') NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS parcels (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, tracking_id VARCHAR(40) NOT NULL UNIQUE,
 sender_name VARCHAR(100) NOT NULL, sender_address VARCHAR(300) NOT NULL,
 sender_city VARCHAR(100) NOT NULL, recipient_name VARCHAR(100) NOT NULL,
 recipient_address VARCHAR(300) NOT NULL, recipient_city VARCHAR(100) NOT NULL,
 weight_kg DECIMAL(10,2) NOT NULL CHECK(weight_kg>0),
 service_type ENUM('STANDARD','EXPRESS') NOT NULL, expected_delivery DATE NOT NULL,
 status VARCHAR(30) NOT NULL, creator_id BIGINT NOT NULL, agent_id BIGINT,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(creator_id) REFERENCES users(id), FOREIGN KEY(agent_id) REFERENCES users(id),
 INDEX ix_agent(agent_id), INDEX ix_status(status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS events (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, parcel_id BIGINT NOT NULL,
 status VARCHAR(30) NOT NULL, location VARCHAR(100) NOT NULL, note VARCHAR(500) NOT NULL,
 actor_id BIGINT NOT NULL, occurred_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(parcel_id) REFERENCES parcels(id), FOREIGN KEY(actor_id) REFERENCES users(id),
 INDEX ix_history(parcel_id,id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id BIGINT NOT NULL, parcel_id BIGINT NOT NULL,
 message VARCHAR(300) NOT NULL, is_read BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(parcel_id) REFERENCES parcels(id)
) ENGINE=InnoDB;
